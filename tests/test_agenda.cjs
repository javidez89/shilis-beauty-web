const assert=require('node:assert/strict');
const M=require('../demo-agenda/model.js');
const r={id:'a',name:'Cliente demo',date:'2026-11-02',time:'09:00',duration:60,professional:'p1',status:'confirmed',phone:''};
assert.equal(M.instant(r),Date.parse('2026-11-02T14:00:00Z'));
assert.equal(M.validate(r),'');
assert.equal(M.conflicts({...r,id:'b',time:'09:30'},[r]).length,1);
assert.equal(M.conflicts({...r,id:'b',time:'10:00'},[r]).length,0);
assert.equal(M.conflicts({...r,id:'b',professional:'p2'},[r]).length,0);
assert.equal(M.conflicts({...r,id:'b'},[{...r,status:'pending'}]).length,0);
assert.equal(M.conflicts(r,[r]).length,0);
assert.ok(M.validate({...r,time:'17:30'}));
assert.ok(M.validate({...r,duration:0}));
assert.ok(M.validate({...r,phone:'123'}));
assert.throws(()=>M.calendarUrl(r));
const url=new URL(M.calendarUrl(r,"agenda@example.com"));
assert.equal(url.searchParams.get('authuser'),'agenda@example.com');
assert.equal(url.searchParams.get('dates'),'20261102T140000Z/20261102T150000Z');
assert.equal(M.whatsappUrl(r),null);
assert.ok(M.whatsappUrl({...r,phone:'3001234567'}).startsWith('https://wa.me/573001234567?'));
console.log('PASS: zona horaria, cruces, profesionales, límites, borrador Calendar y WhatsApp.');
